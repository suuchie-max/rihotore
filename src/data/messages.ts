export function pickMessage(list: string[], seed: string): string {
  // 同じ日は同じメッセージ、日が変わると変わる(seed = 日付など)
  let h = 0;
  for (const ch of seed) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return list[h % list.length];
}
